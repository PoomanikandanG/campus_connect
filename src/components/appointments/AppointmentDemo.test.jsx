// @vitest-environment jsdom
import { act, cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import userEvent from '@testing-library/user-event'
import App from '../../App'
import { navigate } from '../../hooks/useAppPath'
import { APPOINTMENT_STORAGE_KEY } from '../../utils/appointmentStorage'
import { hodDemo } from '../../data/hodDemo'

beforeEach(() => {
  vi.useFakeTimers({ toFake: ['Date'] })
  vi.setSystemTime(new Date('2026-10-21T03:30:00Z'))
  const memory = new Map()
  Object.defineProperty(window, 'localStorage', { configurable: true, value: { getItem: key => memory.get(key) ?? null, setItem: (key, value) => memory.set(key, String(value)), clear: () => memory.clear(), removeItem: key => memory.delete(key) } })
  window.history.replaceState(null, '', '/hod-appointments')
})
afterEach(() => { cleanup(); vi.useRealTimers(); window.localStorage.clear(); window.history.replaceState(null, '', '/') })
const enterStudent = () => fireEvent.click(screen.getByRole('link', { name: /Continue as Demo Student/ }))
const switchHod = () => fireEvent.click(screen.getByRole('link', { name: /Switch to Demo HOD/ }))
const switchStudent = () => fireEvent.click(screen.getByRole('link', { name: /Switch to Demo Student/ }))
function request(time = '10:00 AM') {
  fireEvent.change(screen.getByLabelText('Appointment date'), { target: { value: '2026-10-22' } })
  fireEvent.click(screen.getByRole('radio', { name: time, exact: true }))
  fireEvent.change(screen.getByLabelText('Reason category'), { target: { value: 'Academic guidance' } })
  fireEvent.click(screen.getByRole('button', { name: 'Submit demo request' }))
}
function myRequests() { return screen.getByRole('region', { name: /My Requests/ }) }

describe('complete local appointment demo', () => {
  it('opens both clearly labelled demo modes from the landing page', () => {
    render(<App/>)
    expect(screen.getByText(/Role switching is a simulation/)).toBeTruthy()
    fireEvent.click(screen.getByRole('link', { name: /Continue as Demo HOD/ }))
    expect(screen.getByText('DEMO HOD MODE')).toBeTruthy()
    expect(screen.getByRole('heading', { name: 'Your meeting desk.' })).toBeTruthy()
    switchStudent()
    expect(screen.getByText('DEMO STUDENT MODE')).toBeTruthy()
    expect(screen.getByRole('heading', { name: 'Your appointment desk.' })).toBeTruthy()
    fireEvent.click(screen.getByRole('link', { name: 'Exit Demo' }))
    expect(screen.getByRole('heading', { name: /Meet Your HOD/ })).toBeTruthy()
  })
  it('submits, approves, shows upcoming, persists after remount and confirms cancellation', () => {
    const view = render(<App/>)
    enterStudent()
    request()
    expect(screen.getByRole('status').textContent).toContain('Status: Pending')
    expect(within(myRequests()).getByText('Pending')).toBeTruthy()
    expect(screen.getByText(/No approved upcoming appointments yet/)).toBeTruthy()
    switchHod()
    expect(screen.getByRole('article', { name: /Appointment DEMO-/ })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Approve', exact: true }))
    expect(screen.getByText('Approved', { selector: '.appointment-badge' })).toBeTruthy()
    switchStudent()
    expect(within(screen.getByRole('region', { name: 'Upcoming Appointments' })).getByText('Approved')).toBeTruthy()
    view.unmount()
    render(<App/>)
    expect(within(myRequests()).getByText('Approved')).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Cancel appointment' }))
    expect(within(myRequests()).getByText('Approved')).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Keep request' }))
    expect(screen.queryByRole('button', { name: 'Confirm cancellation' })).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: 'Cancel appointment' }))
    fireEvent.click(screen.getByRole('button', { name: 'Confirm cancellation' }))
    expect(within(myRequests()).getByText('Cancelled')).toBeTruthy()
    expect(screen.getByText(/No approved upcoming appointments yet/)).toBeTruthy()
  })
  it('supports a time proposal and student acceptance, retaining the original until acceptance', () => {
    render(<App/>); enterStudent(); request(); switchHod()
    fireEvent.click(screen.getByRole('button', { name: 'Propose another time' }))
    fireEvent.change(screen.getByLabelText('Proposed date'), { target: { value: '2026-10-22' } })
    const proposal = screen.getByLabelText('Proposed date').closest('form')
    fireEvent.click(within(proposal).getByRole('radio', { name: '2:30 PM', exact: true }))
    fireEvent.click(screen.getByRole('button', { name: 'Send time proposal' }))
    expect(screen.getByText('Reschedule Proposed', { selector: '.appointment-badge' })).toBeTruthy()
    expect(screen.getByText(/22 Oct 2026.*10:00 AM IST/)).toBeTruthy()
    switchStudent()
    fireEvent.click(screen.getByRole('button', { name: 'Accept proposed time' }))
    expect(within(myRequests()).getByText('Approved')).toBeTruthy()
    expect(within(myRequests()).getByText(/22 Oct 2026.*2:30 PM IST/)).toBeTruthy()
  })
  it('lets HODs decline a pending request', () => {
    render(<App/>); enterStudent(); request(); switchHod()
    fireEvent.click(screen.getByRole('button', { name: 'Decline', exact: true }))
    fireEvent.click(screen.getByRole('button', { name: 'Confirm decline' }))
    expect(screen.getByText('Declined', { selector: '.appointment-badge' })).toBeTruthy()
    switchStudent()
    expect(within(myRequests()).getByText('Declined')).toBeTruthy()
  })
  it('lets the selected student reject a proposed time', () => {
    render(<App/>); enterStudent(); request(); switchHod()
    fireEvent.click(screen.getByRole('button', { name: 'Propose another time' }))
    fireEvent.change(screen.getByLabelText('Proposed date'), { target: { value: '2026-10-22' } })
    const form = screen.getByLabelText('Proposed date').closest('form')
    fireEvent.click(within(form).getByRole('radio', { name: '2:30 PM', exact: true }))
    fireEvent.click(screen.getByRole('button', { name: 'Send time proposal' }))
    switchStudent()
    fireEvent.click(screen.getByRole('button', { name: 'Decline proposed time' }))
    fireEvent.click(screen.getByRole('button', { name: 'Confirm decline' }))
    expect(within(myRequests()).getByText('Declined')).toBeTruthy()
    expect(screen.getByText(/No approved upcoming appointments yet/)).toBeTruthy()
  })
  it('preserves an alternate identity and selected HOD while switching modes', () => {
    render(<App/>); enterStudent()
    fireEvent.change(screen.getByLabelText('Demo student identity'), { target: { value: 'demo-student-02' } })
    fireEvent.change(screen.getByLabelText('HOD department'), { target: { value: 'CSE' } })
    request()
    switchHod()
    expect(screen.getByLabelText('Demonstrating HOD').value).toBe(hodDemo[1].id)
    fireEvent.click(screen.getByRole('button', { name: 'Approve', exact: true }))
    switchStudent()
    expect(screen.getByLabelText('Demo student identity').value).toBe('demo-student-02')
    expect(within(myRequests()).getByText('Approved')).toBeTruthy()
  })
  it('prevents double approval for competing students and isolates identities and HOD context', () => {
    render(<App/>); enterStudent(); request()
    fireEvent.change(screen.getByLabelText('Demo student identity'), { target: { value: 'demo-student-02' } })
    expect(screen.getByText(/No requests for this demo student/)).toBeTruthy()
    request(); switchHod()
    const approve = screen.getAllByRole('button', { name: 'Approve', exact: true })
    fireEvent.click(approve[0]); fireEvent.click(screen.getByRole('button', { name: 'Approve', exact: true }))
    expect(screen.getByRole('alert').textContent).toContain('already has an approved appointment')
    expect(screen.getByText('Pending', { selector: '.appointment-badge' })).toBeTruthy()
    fireEvent.change(screen.getByLabelText('Demonstrating HOD'), { target: { value: hodDemo[1].id } })
    expect(screen.queryByRole('article', { name: /Appointment DEMO-/ })).toBeNull()
  })
  it('blocks and re-enables slots across demo modes and filters requests', () => {
    render(<App/>); enterStudent(); request(); switchHod()
    fireEvent.change(screen.getByLabelText('Slot management date'), { target: { value: '2026-10-22' } })
    fireEvent.click(screen.getByRole('button', { name: 'Block 10:00 AM', exact: true }))
    fireEvent.click(screen.getByRole('button', { name: 'Confirm block' }))
    fireEvent.click(screen.getByRole('button', { name: 'Approve', exact: true }))
    expect(screen.getByRole('alert').textContent).toContain('unavailable')
    fireEvent.change(screen.getByLabelText('Filter by status'), { target: { value: 'Approved' } })
    expect(screen.getByText('No requests match these filters.')).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Clear request filters' }))
    switchStudent()
    fireEvent.change(screen.getByLabelText('Appointment date'), { target: { value: '2026-10-22' } })
    expect(screen.queryByRole('radio', { name: '10:00 AM', exact: true })).toBeNull()
    switchHod()
    fireEvent.change(screen.getByLabelText('Slot management date'), { target: { value: '2026-10-22' } })
    fireEvent.click(screen.getByRole('button', { name: 'Re-enable 10:00 AM', exact: true }))
    switchStudent()
    fireEvent.change(screen.getByLabelText('Appointment date'), { target: { value: '2026-10-22' } })
    expect(screen.getByRole('radio', { name: '10:00 AM', exact: true })).toBeTruthy()
  })
  it('shows required fields, supports keyboard and excludes Sundays and past dates', async () => {
    render(<App/>); enterStudent()
    expect(screen.getByLabelText('Reason category').required).toBe(true)
    expect(screen.getByLabelText('Appointment date').min).toBe('2026-10-21')
    fireEvent.change(screen.getByLabelText('Appointment date'), { target: { value: '2026-10-25' } })
    expect(screen.queryAllByRole('radio')).toHaveLength(0)
    fireEvent.change(screen.getByLabelText('Appointment date'), { target: { value: '2026-10-20' } })
    expect(screen.queryAllByRole('radio')).toHaveLength(0)
    screen.getByLabelText('Demo student identity').focus()
    await userEvent.setup().tab()
    expect(document.activeElement).toBe(screen.getByLabelText('HOD department'))
  })
  it('handles corrupt storage without silently replacing it and supports confirmed reset', () => {
    window.localStorage.setItem(APPOINTMENT_STORAGE_KEY, '{broken')
    render(<App/>)
    expect(screen.getByRole('alert').textContent).toContain('saved copy has not been overwritten')
    expect(window.localStorage.getItem(APPOINTMENT_STORAGE_KEY)).toBe('{broken')
    fireEvent.click(screen.getByRole('button', { name: 'Reset demo data' }))
    fireEvent.click(screen.getByRole('button', { name: 'Confirm reset' }))
    expect(JSON.parse(window.localStorage.getItem(APPOINTMENT_STORAGE_KEY)).requests).toEqual([])
    expect(screen.queryByRole('alert')).toBeNull()
  })
  it('supports direct demo paths and browser history navigation back to the faculty directory', () => {
    window.history.replaceState(null, '', '/hod-appointments/hod')
    render(<App/>)
    expect(screen.getByText('DEMO HOD MODE')).toBeTruthy()
    act(() => navigate('/hod-appointments/student'))
    expect(screen.getByText('DEMO STUDENT MODE')).toBeTruthy()
    fireEvent.click(screen.getByRole('link', { name: 'Faculty Directory', exact: true }))
    expect(screen.getByRole('search')).toBeTruthy()
    act(() => { window.history.replaceState(null, '', '/hod-appointments/hod'); window.dispatchEvent(new PopStateEvent('popstate')) })
    expect(screen.getByText('DEMO HOD MODE')).toBeTruthy()
  })
})
